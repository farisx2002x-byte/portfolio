/* علامات المنع: الملف لا يُنشر كما هو مهما كان نوعه */
const PRIVATE = /لا تنشر|لا يُنشر|الرقم الجامعي|رقم الهوية|الجوال|صور الزملاء|أسماء الزملاء|أسماء وصور|عند الطلب فقط/;

/* أنواع الملفات حسب أول كلمة (أو الصيغة) */
const KINDS = [
  [/^\d{2}\s*-\s*/, "summary"],                 // 01 - … (ملخص جاهز للموقع)
  [/^عرض كامل/, "full"],                        // الأصل الكامل: عند الطلب فقط
  [/^عرض أصلي|^ملف المصدر|^ملف PDF/, "original"],
  [/^لوحات يدوية/, "hand"],
  [/^لوحة المشروع|^لوحات معرض|^لوحات\b|^لوحة\b/, "board"],
  [/^بوستر|^بوسترين/, "poster"],
  [/^رندر/, "render"],
  [/^صورة درون/, "drone"],
  [/^خريطة/, "map"],
  [/^بيانات/, "data"],
  [/^شهادة تطوع|^سجل التطوع/, "volunteer"],
  [/^شهادة|^كل شهادات/, "certificate"],
  [/^سيرة ذاتية/, "cv"],
  [/^كتيب/, "booklet"],
  [/^الصورة الشخصية/, "photo"],
  [/^صورة غلاف|^غلاف/, "cover"],
];

/** يصنّف اسم ملف: النوع، رقم الملخص، وهل يجوز نشره */
export function classify(name) {
  const base = String(name || "").replace(/\.[a-z0-9]+$/i, "").trim();
  let kind = "other";
  for (const [re, k] of KINDS) if (re.test(base)) { kind = k; break; }
  const n = kind === "summary" ? Number(base.match(/^(\d{2})/)[1]) : null;
  const privateFlag = PRIVATE.test(base) && !/مخفي|للموقع|بدون الرقم|بدون الجوال|بلا الرقم|بلا جوال/.test(base); // «نسخة للموقع (الرقم الجامعي مخفي)» تُنشر
  // ما لا يُنشر أبداً: الأصول الكاملة والمصدر، وكل ما يحمل تحذيراً، والسيرة الذاتية التي فيها الجوال
  const publishable = !privateFlag && !["full", "original"].includes(kind);
  return { kind, number: n, publishable, privateFlag, base };
}

/** أين يذهب ملف وصل إلى صندوق الوارد؟ (اقتراح فرز للتقرير، لا نقل تلقائياً) */
export function inboxSuggestion(name) {
  const c = classify(name);
  const dest = {
    summary: "01 الملخصات الجاهزة للموقع", full: "02 المشاريع/<مجلد المشروع>", original: "02 المشاريع/<مجلد المشروع>",
    hand: "03 البوسترات واللوحات", board: "03 البوسترات واللوحات", poster: "03 البوسترات واللوحات",
    render: "02 المشاريع/<مجلد المشروع>", drone: "08 تصوير الدرون الخام (أو مجلد المشروع)", map: "07 خرائط وملفات GIS", data: "07 خرائط وملفات GIS",
    volunteer: "04 الشهادات والتطوع", certificate: "04 الشهادات والتطوع", cv: "05 الملف الشخصي والسيرة الذاتية", booklet: "05 الملف الشخصي والسيرة الذاتية",
    photo: "05 الملف الشخصي والسيرة الذاتية", cover: "05 الملف الشخصي والسيرة الذاتية", other: "— (الاسم لا يبدأ بكلمة معروفة: سمِّه ثم أعد المزامنة)",
  }[c.kind];
  return { ...c, dest, note: c.privateFlag ? "يحمل تحذيراً في اسمه: لن يُنشر كما هو" : c.kind === "summary" ? `ملخص رقم ${String(c.number).padStart(2, "0")}: اربطه بمشروع عبر عمود summary_file في الجدول` : "" };
}

/** الصور القابلة للنشر داخل مجلد مشروع (رندرات وصور درون) مرتبة بالاسم */
export function galleryFiles(files) {
  return (files || []).filter((f) => { const c = classify(f.name || f.title); return c.publishable && ["render", "drone"].includes(c.kind) && /\.(jpe?g|png|webp)$/i.test(f.name || f.title); })
    .sort((a, b) => (a.name || a.title).localeCompare(b.name || b.title, "ar"));
}

/** تسمية رندر → تعليق قصير: «رندر 01 - ساحة المسجد» ← «ساحة المسجد» */
export function captionOf(name) { const m = String(name).replace(/\.[a-z0-9]+$/i, "").match(/^(?:رندر|صورة درون)\s*\d+\s*-\s*(.+)$/); return m ? m[1].trim() : ""; }
